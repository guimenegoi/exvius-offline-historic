"""Generate only the pinned GL9 native exports needed by our Frida scripts.

The original GL9 ARM64 client is the source of truth. No symbol offset is
guessed from runtime screenshots, prior builds, or external symbol databases.
"""
from __future__ import annotations

import hashlib
import re
import subprocess
import tempfile
from pathlib import Path
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[2]
JS_DIR = Path(__file__).resolve().parent
APK = ROOT / "release/exvius-offline-v0.1.24.apk"
OUTPUT = JS_DIR / "gl9_export_offsets.js"
EXPECTED_SHA256 = "a127654037f2f28a70cce7c64ff0a9d291770ea904cdf5bcba59a7af9a6937e4"

# Built by concat in summon_menu.js; their mangled names are not necessarily
# present as contiguous source string literals.
DYNAMIC_SCENE_PREFIXES = (
    "_ZN13GachaTopScene",
    "_ZN9GateScene",
    "_ZN9HomeScene",
)


def generate() -> str:
    with ZipFile(APK) as archive:
        binary = archive.read("lib/arm64-v8a/libgame.so")
    digest = hashlib.sha256(binary).hexdigest()
    if digest != EXPECTED_SHA256 or binary[:4] != b"\x7fELF" or binary[18:20] != b"\xb7\x00":
        raise ValueError("Pinned Global 9.0.0 ARM64 libgame.so has changed")
    with tempfile.TemporaryDirectory(prefix="ffbe-gl9-symbols-") as folder:
        native = Path(folder) / "libgame.so"
        native.write_bytes(binary)
        raw = subprocess.run(
            ["nm", "-D", "--defined-only", str(native)],
            check=True, text=True, capture_output=True,
        ).stdout
    exports = {}
    for row in raw.splitlines():
        match = re.match(r"^([0-9a-fA-F]+) [A-Za-z] (\S+)$", row)
        if match:
            exports[match.group(2)] = int(match.group(1), 16)
    runtime = "\n".join(
        file.read_text(encoding="utf-8")
        for file in sorted(JS_DIR.glob("*.js"))
        if not file.name.startswith("test_")
        and file.name != OUTPUT.name
    )
    source_tokens = {
        name for name in re.findall(r"_Z[A-Za-z0-9_]+", runtime)
        if len(name) >= 7
    }
    exact = {name for name in source_tokens if name in exports}
    partial = {name for name in source_tokens if name not in exports}
    # summon_menu.js creates C++ response method names using
    # name.length + name. Include the exact class families found in source
    # rather than silently dropping their dynamically constructed exports.
    response_classes = set(re.findall(
        r"['\"]([A-Za-z][A-Za-z0-9]*Response)['\"]", runtime
    ))
    dynamic_responses = {
        "_ZN" + str(len(name)) + name for name in response_classes
    }
    prefixes = partial | set(DYNAMIC_SCENE_PREFIXES) | dynamic_responses
    selected = {
        name for name in exports
        if name in exact or any(name.startswith(prefix) for prefix in prefixes)
    }
    # This original GL9 binary itself exports __dynamic_cast. Resolving it
    # through Module.getGlobalExportByName fails under Houdini because the
    # ARM64 module is absent from Frida's normal module enumeration.
    selected.update(name for name in ("__dynamic_cast", "_Znwm") if name in exports)
    expected = {
        "_ZN10TitleScene9setLayoutEv": 0x1e5b51c,
        "_ZN9HomeScene9setLayoutEv": 0x1e49e34,
        "__dynamic_cast": 0x2dba408,
        "_ZN20TfaEventInfoResponse9readParamEiiPKcS1_b": 0x193d8d8,
    }
    selected.update(expected)
    if len(selected) < 400 or len(selected) > 5000:
        raise ValueError(f"Unexpected GL9 native symbol index size: {len(selected)}")
    for name, offset in expected.items():
        if exports.get(name) != offset or name not in selected:
            raise ValueError(f"Invalid pinned GL9 export: {name}")
    lines = [
        "// AUTOGENERATED by generate_gl9_offsets.py; do not edit by hand.",
        "// Original Final Fantasy Brave Exvius Global 9.0.0, ARM64.",
        "// libgame.so SHA-256: " + EXPECTED_SHA256,
        "// ELF st_value offsets. Only used when Frida cannot enumerate a",
        "// libgame.so mapped under Android's native ARM translation bridge.",
        "export const GL9_OFFSETS = Object.freeze({",
    ]
    lines.extend(f"  {name!r}: 0x{exports[name]:x}," for name in sorted(selected))
    lines.append("});")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    generated = generate()
    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"Generated {OUTPUT}: {generated.count('0x'):,} offsets, "
          f"{len(generated):,} bytes")
